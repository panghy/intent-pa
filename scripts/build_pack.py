#!/usr/bin/env python3
"""Generate standalone Intent specialist prompts; no runtime includes are needed."""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EXPECTED_IDS = {
    "pa-ada", "pa-tempo", "pa-quill", "pa-atlas", "pa-scout", "pa-haven",
    "pa-ledger", "pa-keeper", "pa-sentinel", "pa-steward", "pa-auditor",
}
FRONTMATTER_KEYS = {"name", "description", "role", "roleReminder", "teamAgents"}


def load_sources(root=ROOT):
    config = json.loads((root / "source/pack.json").read_text(encoding="utf-8"))
    version = config["charterVersion"]
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError("charterVersion must be a semantic version")
    roles = config["specialists"]
    ids = [role["id"] for role in roles]
    if len(ids) != len(EXPECTED_IDS) or set(ids) != EXPECTED_IDS:
        raise ValueError("Expected exactly the eleven unique pa-* specialist IDs")
    for role in roles:
        expected_role = "orchestrator" if role["id"] == "pa-ada" else "internal"
        if role["role"] != expected_role:
            raise ValueError(f"Invalid role for {role['id']}")
        if set(role) != {"id", "name", "description", "role", "roleReminder"}:
            raise ValueError(f"Unsupported specialist metadata for {role['id']}")
        for key in ("name", "description", "roleReminder"):
            if not isinstance(role[key], str) or not role[key].strip():
                raise ValueError(f"Missing {key} for {role['id']}")
    charter = (root / "source/charter.md").read_text(encoding="utf-8").strip()
    if not charter:
        raise ValueError("Shared charter must not be empty")
    return version, roles, charter


def render(root=ROOT):
    version, roles, charter = load_sources(root)
    result = {}
    for role in roles:
        identifier = role["id"]
        metadata = {k: v for k, v in role.items() if k != "id"}
        if identifier == "pa-ada":
            metadata["teamAgents"] = [r["id"] for r in roles if r["id"] != identifier]
        frontmatter = "\n".join(
            f"{key}: {json.dumps(value, ensure_ascii=False)}"
            for key, value in metadata.items()
        )
        instructions = (root / "source/roles" / f"{identifier}.md").read_text(encoding="utf-8").strip()
        if not instructions:
            raise ValueError(f"Empty role instructions: {identifier}")
        body = (
            f"<!-- Generated by scripts/build_pack.py; edit source files. -->\n\n"
            f"Charter version: {version}\n\n{charter}\n\n{instructions}\n"
        )
        result[f"{identifier}.md"] = f"---\n{frontmatter}\n---\n\n{body}"
    return result


def parse_generated(content):
    """Strict validator of our JSON-valued frontmatter subset, not Intent's parser."""
    if not content.startswith("---\n") or "\n---\n" not in content[4:]:
        raise ValueError("Missing frontmatter delimiters")
    header, body = content[4:].split("\n---\n", 1)
    metadata = {}
    for line in header.splitlines():
        key, value = line.split(":", 1)
        if key not in FRONTMATTER_KEYS or key in metadata:
            raise ValueError(f"Unsupported or repeated frontmatter field: {key}")
        metadata[key] = json.loads(value)
    if not {"name", "description", "role", "roleReminder"} <= metadata.keys():
        raise ValueError("Missing required frontmatter")
    return metadata, body.strip()


def validate(root=ROOT):
    expected = render(root)
    directory = root / "specialists"
    actual = {p.name for p in directory.iterdir()} if directory.exists() else set()
    if actual != set(expected):
        raise ValueError("Specialist directory must contain exactly the eleven generated files")
    for filename, content in expected.items():
        actual_content = (directory / filename).read_text(encoding="utf-8")
        if actual_content != content:
            raise ValueError(f"Generated prompt differs from source: {filename}; run make build")
        metadata, _ = parse_generated(actual_content)
        if filename == "pa-ada.md":
            roster = metadata["teamAgents"]
            if len(roster) != 10 or set(roster) != EXPECTED_IDS - {"pa-ada"}:
                raise ValueError("Ada's roster must contain every worker once")
        elif "teamAgents" in metadata:
            raise ValueError(f"Worker must not declare a roster: {filename}")
    return len(expected)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail on missing, extra or stale artifacts")
    args = parser.parse_args()
    if not args.check:
        files = render()
        directory = ROOT / "specialists"
        directory.mkdir(exist_ok=True)
        extra = {p.name for p in directory.iterdir()} - files.keys()
        if extra:
            raise SystemExit(f"Unexpected files in specialists; remove intentionally: {sorted(extra)}")
        for filename, content in files.items():
            (directory / filename).write_text(content, encoding="utf-8")
    try:
        count = validate()
    except (ValueError, KeyError, OSError) as exc:
        raise SystemExit(str(exc)) from exc
    print(f"Validated {count} specialists with the complete shared charter")


if __name__ == "__main__":
    main()
